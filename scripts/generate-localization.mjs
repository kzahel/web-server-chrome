/** Deterministic runtime output: only registered catalogs enter release assets. */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "@formatjs/icu-messageformat-parser";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export function generatedFiles() {
  const registry = JSON.parse(
    fs.readFileSync(path.join(root, "localization/locales.json"), "utf8"),
  );
  const locales = registry.supportedLocales.web;
  const catalogs = Object.fromEntries(
    locales.map((locale) => {
      const source = JSON.parse(
        fs.readFileSync(
          path.join(root, `localization/catalogs/web/${locale}.json`),
          "utf8",
        ),
      );
      return [
        locale,
        Object.fromEntries(
          Object.entries(source).map(([key, row]) => [
            key,
            parse(row.defaultMessage),
          ]),
        ),
      ];
    }),
  );
  const files = new Map([
    [
      "packages/i18n/src/generated.ts",
      `// Generated by scripts/generate-localization.mjs. Do not edit.\nimport type { MessageFormatElement } from "@formatjs/icu-messageformat-parser";\nexport type MessageId = ${Object.keys(
        catalogs.en,
      )
        .map((id) => JSON.stringify(id))
        .join(
          " | ",
        )};\nexport const supportedLocales: readonly string[] = ${JSON.stringify(locales)};\nexport const catalogs: Record<string, Record<string, MessageFormatElement[]>> = ${JSON.stringify(catalogs, null, 2)};\n`,
    ],
  ]);
  for (const locale of registry.supportedLocales.extension) {
    const values = JSON.parse(
      fs.readFileSync(
        path.join(root, `localization/catalogs/extension/${locale}.json`),
        "utf8",
      ),
    );
    files.set(
      `extension/public/_locales/${locale.replaceAll("-", "_")}/messages.json`,
      `${JSON.stringify(Object.fromEntries(Object.entries(values).map(([key, value]) => [key, { message: value }])), null, 2)}\n`,
    );
  }
  files.set(
    "ios/localization.generated.yml",
    `# Generated by scripts/generate-localization.mjs. Do not edit.\noptions:\n  knownRegions: ${JSON.stringify(registry.supportedLocales.ios)}\n`,
  );
  const nativeLocales = registry.supportedLocales.desktop;
  files.set(
    "desktop/common/src/generated_localization.rs",
    `// Generated by scripts/generate-localization.mjs. Do not edit.\n#[rustfmt::skip]\nconst CATALOGS: &[(&str, &str)] = &[\n${nativeLocales.map((locale) => `    ("${locale}", include_str!("../../../localization/catalogs/desktop/${locale}.json")),`).join("\n")}\n];\n`,
  );
  const androidLocales = registry.supportedLocales.android;
  files.set(
    "localization/generated/android-locales.txt",
    `${androidLocales.map((locale) => locale.replace(/-([A-Z]{2})$/, "-r$1")).join("\n")}\n`,
  );
  files.set(
    "android/app/src/main/java/app/ok200/android/ui/SupportedLanguages.kt",
    `// Generated by scripts/generate-localization.mjs. Do not edit.\npackage app.ok200.android.ui\n\nobject SupportedLanguages {\n    val tags = listOf(${androidLocales.map((locale) => JSON.stringify(locale)).join(", ")})\n}\n`,
  );
  const nativeCatalog = (locale) =>
    JSON.parse(
      fs.readFileSync(
        path.join(root, `localization/catalogs/desktop/${locale}.json`),
        "utf8",
      ),
    );
  const original = fs
    .readFileSync(
      path.join(
        root,
        "desktop/crostini/resources/app.ok200.crostini.desktop.in",
      ),
      "utf8",
    )
    .replace(/^(GenericName|Comment)\[[^\]]+\]=.*\n/gm, "");
  const english = nativeCatalog("en");
  const launcher = nativeLocales
    .filter((locale) => locale !== "en")
    .flatMap((locale) => {
      const target = nativeCatalog(locale);
      return ["GenericName", "Comment"].map((field) => {
        const source =
          field === "GenericName"
            ? "Web Server"
            : "Open 200 OK Web Server for ChromeOS Linux";
        const key = Object.keys(english).find((key) => english[key] === source);
        if (!key || !target[key])
          throw new Error(`Missing launcher metadata: ${locale}/${field}`);
        return `${field}[${locale.replaceAll("-", "_")}]=${target[key]}`;
      });
    });
  files.set(
    "desktop/crostini/resources/app.ok200.crostini.desktop.in",
    original + (launcher.length ? `${launcher.join("\n")}\n` : ""),
  );
  return files;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const [file, expected] of generatedFiles()) {
    const location = path.join(root, file);
    if (process.argv.includes("--check")) {
      if (
        !fs.existsSync(location) ||
        fs.readFileSync(location, "utf8") !== expected
      )
        throw new Error(`Generated locale output is stale: ${file}`);
    } else {
      fs.mkdirSync(path.dirname(location), { recursive: true });
      fs.writeFileSync(location, expected);
    }
  }
}
